"""The bundled sample source: a small exercise-platform database.

Fictional organizations run tabletop exercises; each exercise has runs;
each run produces an ordered stream of events and a set of findings. A few
finding titles deliberately recur across runs - recurrence is the
interesting question an ontology layer should answer well.

The sample is generated by this module (no binary blob in the repo) so a
fresh clone can build it with one command: ``ontos sample``.
"""

