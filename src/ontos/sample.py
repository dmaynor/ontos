def create_sample_db(path: str | Path, force: bool = False) -> dict:
    """Create the sample SQLite database. Returns row counts per table."""
    path = Path(path)
    if path.exists():
        if not force:
            raise FileExistsError(f"sample database already exists: {path} (use --force)")
        path.unlink()
    conn = sqlite3.connect(path)
    try:
        conn.executescript(SCHEMA)
        conn.executemany("INSERT INTO organizations VALUES(?,?,?,?,?)", ORGANIZATIONS)
        conn.executemany("INSERT INTO exercises VALUES(?,?,?,?,?)", EXERCISES)
        conn.executemany("INSERT INTO runs VALUES(?,?,?,?,?,?)", RUNS)
        conn.executemany(
            "INSERT INTO findings(run_id, title, category, severity, owner, status, created_at) "
            "VALUES(?,?,?,?,?,?,?)",
            FINDINGS,
        )
        conn.executemany(
            "INSERT INTO events(run_id, occurred_at, kind, actor, summary) VALUES(?,?,?,?,?)",
            EVENTS,
        )
        conn.commit()
        counts = {}
        for table in ("organizations", "exercises", "runs", "events", "findings"):
            counts[table] = conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        return counts
    finally:
        conn.close()
